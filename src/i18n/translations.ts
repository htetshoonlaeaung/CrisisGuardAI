export type TranslationKey = string;

const missingTranslationWarnings = new Set<string>();

function isDevMode(): boolean {
  return Boolean((import.meta as ImportMeta & { env?: { DEV?: boolean } }).env?.DEV);
}

function warnMissingTranslation(key: string): void {
  if (!isDevMode() || missingTranslationWarnings.has(key)) return;
  missingTranslationWarnings.add(key);
  console.warn(`[i18n] Missing Myanmar translation: ${key}`);
}

function getNested(obj: any, path: string): string | undefined {
  return path.split('.').reduce((acc, part) => acc?.[part], obj);
}

export function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));
}

export function translate(lang: Language, key: TranslationKey, vars?: Vars): string {
  const localizedTemplate = getNested(translations[lang], key);
  if (lang === 'my' && localizedTemplate === undefined) {
    warnMissingTranslation(key);
  }
  const template = localizedTemplate ?? getNested(translations.en, key) ?? key;
  return interpolate(template, vars);
}

export function translateDomain(lang: Language, domain: CrisisDomain | 'all' | string): string {
  return translate(lang, `domain.${domain}`);
}

export function translateSeverity(lang: Language, severity: TriageSeverity, compact = false): string {
  return translate(lang, compact ? `severity.compact.${severity}` : `severity.${severity}`);
}
